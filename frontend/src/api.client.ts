  //////////////// GAMES /////////////

  // a page can have the same game many times (like activity rows), they share one request
  private static requests = new Map<string, Promise<unknown>>();

  private static async shared<T>(
    key: string,
    fetch: () => Promise<T>,
  ): Promise<T> {
    let request = this.requests.get(key) as Promise<T> | undefined;
    if (!request) {
      request = fetch();
      this.requests.set(key, request);
    }
    try {
      return await request;
    } finally {
      this.requests.delete(key);
    }
  }

  static async getGame(game_id: number): Promise<SingleGame> {
    const key = `api_getGame_${game_id}`;
    const cached = getCached<SingleGame>(key);
    if (cached) {
      return cached;
    }
    return this.shared(key, async () => {
      const { data, error } = await this.client.GET("/game/{game_id}", {
        params: { path: { game_id } },
      });
      if (error) {
        console.error("Error fetching game:", error);
        throw error;
      }
      setCached(key, data);
      return data;
    });
  }

  /** where the cover is from. The image itself is at gameCoverUrl */
  static async getGameCover(game_id: number): Promise<GameCover> {
    // starts with gameCover_{id}_ so clearCachedGame clears it
    const key = `gameCover_${game_id}_info`;
    const cached = getCached<GameCover>(key, COVER_MAX_AGE);
    if (cached) {
      return cached;
    }
    return this.shared(key, async () => {
      const { data, error } = await this.client.GET("/game/{game_id}/cover", {
        params: { path: { game_id } },
      });
      if (error) {
        console.error("Error fetching game cover:", error);
        throw error;
      }
      setCached(key, data);
      return data;
    });
  }

  /** the cover image, for an img src. 404 if the game has none */
  static gameCoverUrl(
    game_id: number,
    version: keyof GameCover["versions"],
  ): string {
    const url = `/api/game/${game_id}/cover/${version}`;
    // the browser keeps it a while, a new version after an admin changed the cover
    const changed = coverChanged(game_id);
    return changed ? `${url}?v=${changed}` : url;
  }

